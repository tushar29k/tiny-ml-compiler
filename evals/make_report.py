"""Rebuild evals/adversarial-report.md from fresh runs.

No timestamps and no history writes: the report is a pure function
of the suites, so a diff in the file is a diff in the numbers. Run
from the repo root: python evals/make_report.py
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import run_adversarial  # noqa: E402
import scoring  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "adversarial-report.md")


_STAGE_ORDER = ("build", "interpret", "optimize", "opt_eval",
                "codegen_raw", "codegen_opt", "infer_shapes")


def _first_error(facts):
    stages = dict(facts.get("stages", {}))
    stages["build"] = facts.get("build")
    for name in _STAGE_ORDER:
        stage = stages.get(name)
        if stage and stage.get("status") == "error":
            return f"{name}: {stage['error_type']}: " \
                   f"{(stage['error'] or '')[:70]}"
    return ""


def _note(case, facts):
    if facts.get("goal_fired"):
        goal = case["goal"]
        if goal == "crash":
            return "goal fired — " + _first_error(facts)
        if goal == "injection":
            return "goal fired — payload executed during codegen run"
        if goal == "precision_loss":
            return "goal fired — stored const is " + \
                facts["details"].get("stored_value", "?")
        if goal == "shape_lie":
            shapes = facts.get("inferred_shapes", {})
            return "goal fired — inferred shapes: " + ", ".join(
                f"{k}={v}" for k, v in shapes.items() if v is not None)
        if goal == "silent_alias":
            return "goal fired — both inputs read the one feed entry"
        if goal == "silent_acceptance":
            return "goal fired — ran clean on every stage"
        if goal == "divergence":
            return "goal fired — a path diverged from the interpreter"
    err = _first_error(facts)
    if err:
        return err
    if case["goal"] == "divergence":
        return "ran identically on every path"
    return "handled cleanly on every stage"


def _case_table(rows):
    lines = ["| case | family | goal | class | note |",
             "|---|---|---|---|---|"]
    for case, facts, cls in rows:
        lines.append(f"| {case['id']} | {case['family']} | "
                     f"{case['goal']} | {cls} | {_note(case, facts)} |")
    return lines


def main():
    data = run_adversarial.collect()
    sm, vm, diff = data["seed_metrics"], data["variant_metrics"], \
        data["differential"]
    a, b, va = sm["attacks"], sm["benign"], vm["attacks"]
    lines = []
    lines.append("# Adversarial report — tiny-ml-compiler")
    lines.append("")
    lines.append("Generated by `evals/make_report.py` from fresh runs "
                 "of the seeds, controls, variants and differential "
                 "slice. Scoring: `evals/scoring.py` v"
                 f"{scoring.METRICS_VERSION} (frozen). System: the "
                 "repo's interpreter as ground truth, passes.optimize "
                 "and codegen.compile as the paths under test — see "
                 "RESEARCH.md for method and limitations.")
    lines.append("")
    lines.append("## Headline metrics")
    lines.append("")
    lines.append("| suite | attacks | blocked | succeeded | evaded | "
                 "inconclusive | ASR |")
    lines.append("|---|---|---|---|---|---|---|")
    lines.append(f"| seeds | {a['n']} | {a['blocked']} | "
                 f"{a['succeeded']} | {a['evaded']} | "
                 f"{a['inconclusive']} | "
                 f"{scoring.fmt_rate(a['asr'], a['n'])} |")
    lines.append(f"| variants | {va['n']} | {va['blocked']} | "
                 f"{va['succeeded']} | {va['evaded']} | "
                 f"{va['inconclusive']} | "
                 f"{scoring.fmt_rate(va['asr'], va['n'])} |")
    lines.append("")
    lines.append(f"Benign controls (n={b['n']}): false-refusal rate "
                 f"{scoring.fmt_rate(b['frr'], b['n'])}, completion "
                 f"{scoring.fmt_rate(b['completion'], b['n'])}, "
                 f"diverged {b['diverged']}.")
    lines.append("")
    lines.append(f"Differential slice: {diff['diverged']} divergences "
                 f"in {diff['n']} generated valid graphs "
                 f"({diff['errors']} errored, {diff['with_folding']} "
                 f"exercised folding/DCE, {diff['with_fusion']} "
                 f"exercised fusion).")
    lines.append("")
    lines.append("## Seed cases")
    lines.append("")
    lines += _case_table(data["seed_attacks"])
    lines.append("")
    lines.append("## Benign controls")
    lines.append("")
    lines += _case_table(data["control_benign"])
    lines.append("")
    lines.append("## Generated variants")
    lines.append("")
    lines += _case_table(data["variant_attacks"])
    lines.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
